-- Council." This exact fallback is codified in the town's own (more
-- current) Section 209(c): "...or if a special election is cancelled due
-- to a lack of valid candidates, the mayor shall appoint, within
-- forty-five (45) days after the declaration of the vacancy and with
-- confirmation by a majority of the remaining council members, a
-- qualified person from the ward..." The town's own individual Ward 5 page
