-- WARD 5 -- A CAUGHT STALE-DATA TRAP, RESOLVED: both an aggregated
-- WebSearch summary AND a direct WebFetch of the Maryland Manual's own
-- live page reported Ward 5 as simply "vacant" ("no candidate ran in the
-- May 2025 election"). That was true at first, but is now STALE. Charter
-- Section 209(a) declares a vacancy "if no one is elected in an election";
-- the town then attempted the charter-mandated special election (filing
