-- Section 702 explicitly tagged "[Amended 5-2-16, effective 6-21-16]",
-- rewriting the mayor's role to a largely ceremonial one (still a directly
-- elected, VOTING member and chair of the 7-member council) and vesting
-- true chief-executive authority in a council-appointed Town Manager --
-- i.e. a genuine council-manager government, matching the town's own
-- current self-description on riverdaleparkmd.gov/government/. The mgaleg
-- reprint appears simply not to have incorporated this 2016 amendment
-- despite bearing later revision-date footers elsewhere in the same
-- document (an inconsistency in the state's own reprint, not a case of the
-- town's document being the stale one for THIS article -- for Article V's
-- 2018 ward-redistricting-review amendment, conversely, the mgaleg copy IS
-- the more current of the two). Neither Article IV/VII framing changes any
-- office/politician row modeled below, since the Mayor is directly elected
-- either way; this is disclosed because it directly bears on how the
-- Mayor's role is described.
