/** Tiny {placeholder} interpolator -- mobile's screens build a handful of
 *  templated strings (progress counts, dates, names) that don't fit a
 *  static dictionary value. Same idea as sprintf, deliberately minimal. */
export function tf(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
